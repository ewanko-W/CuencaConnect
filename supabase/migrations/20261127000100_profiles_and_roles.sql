-------------------------------------------------------------------------------
-- Profiles
-------------------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  role public.user_role not null default 'resident',
  office_id smallint references public.offices (id),
  display_name text not null check (char_length(btrim(display_name)) between 2 and 60),
  barangay_id smallint references public.barangays (id),
  verification_status public.verification_status not null default 'unverified',
  consent_version text,
  consented_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_office_staff_has_office
    check ((role = 'office_staff') = (office_id is not null)),
  constraint profiles_resident_consent
    check (role <> 'resident' or (consent_version is not null and consented_at is not null)),
  constraint profiles_resident_barangay
    check (role <> 'resident' or barangay_id is not null)
);

comment on table public.profiles is
  'One row per user. Data minimization: no phone, address, birth date, or ID number.';

create index profiles_role_idx on public.profiles (role);
create index profiles_office_idx on public.profiles (office_id) where office_id is not null;

-------------------------------------------------------------------------------
-- Consent version (single source of truth; the client must send the same value)
-------------------------------------------------------------------------------
create function public.current_consent_version()
returns text
language sql
immutable
set search_path = ''
as $$ select '2026-11-v1'::text $$;

-------------------------------------------------------------------------------
-- Role helpers. SECURITY DEFINER avoids RLS recursion when used in policies.
-------------------------------------------------------------------------------
create function public.current_user_role()
returns public.user_role
language sql
stable
security definer
set search_path = ''
as $$
  select p.role from public.profiles p where p.id = auth.uid()
$$;

create function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(public.current_user_role() = 'admin', false)
$$;

create function public.is_office_staff()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(public.current_user_role() = 'office_staff', false)
$$;

create function public.my_office_id()
returns smallint
language sql
stable
security definer
set search_path = ''
as $$
  select p.office_id from public.profiles p where p.id = auth.uid()
$$;

create function public.is_verified()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid()
      and p.role = 'resident'
      and p.verification_status = 'approved'
  )
$$;

-------------------------------------------------------------------------------
-- Profile creation on sign-up
-------------------------------------------------------------------------------
create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  user_meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  app_meta jsonb := coalesce(new.raw_app_meta_data, '{}'::jsonb);
  provisioned_role text := nullif(app_meta ->> 'cc_role', '');
  v_display_name text := nullif(btrim(user_meta ->> 'display_name'), '');
begin
  -- Manual provisioning of staff. app_metadata can only be written with the
  -- service role or SQL, never by the public sign-up endpoint.
  if provisioned_role is not null then
    if provisioned_role not in ('admin', 'office_staff') then
      raise exception 'Invalid provisioned role: %', provisioned_role
        using errcode = 'check_violation';
    end if;

    insert into public.profiles (id, role, office_id, display_name)
    values (
      new.id,
      provisioned_role::public.user_role,
      nullif(app_meta ->> 'cc_office_id', '')::smallint,
      coalesce(v_display_name, split_part(new.email, '@', 1))
    );
    return new;
  end if;

  -- Public sign-up: always a resident, and consent is mandatory.
  if coalesce(user_meta ->> 'consent_given', 'false') <> 'true'
     or coalesce(user_meta ->> 'consent_version', '') <> public.current_consent_version() then
    raise exception 'Consent to the current privacy notice is required to register'
      using errcode = 'check_violation';
  end if;

  insert into public.profiles (id, role, display_name, barangay_id, consent_version, consented_at)
  values (
    new.id,
    'resident',
    v_display_name,
    nullif(user_meta ->> 'barangay_id', '')::smallint,
    public.current_consent_version(),
    now()  -- server time, not client-supplied
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-------------------------------------------------------------------------------
-- Protect sensitive profile columns (defense in depth with column grants).
-- SECURITY INVOKER on purpose: current_user is the API role for client calls
-- and the function owner inside SECURITY DEFINER RPCs (e.g., review_verification).
-------------------------------------------------------------------------------
create function public.guard_profile_update()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if current_user in ('anon', 'authenticated') and (
       new.id is distinct from old.id
    or new.role is distinct from old.role
    or new.office_id is distinct from old.office_id
    or new.verification_status is distinct from old.verification_status
    or new.consent_version is distinct from old.consent_version
    or new.consented_at is distinct from old.consented_at
    or new.created_at is distinct from old.created_at
  ) then
    raise exception 'Protected profile fields cannot be changed'
      using errcode = 'insufficient_privilege';
  end if;

  new.updated_at := now();
  return new;
end;
$$;

create trigger profiles_guard_update
  before update on public.profiles
  for each row execute function public.guard_profile_update();

create function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger offices_touch_updated_at
  before update on public.offices
  for each row execute function public.touch_updated_at();

