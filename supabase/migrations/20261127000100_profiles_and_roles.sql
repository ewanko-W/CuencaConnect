create table public.offices (
  id smallint generated by default as identity primary key,
  code text not null unique check (code ~ '^[A-Z]{2,12}$'),
  name text not null unique check (char_length(btrim(name)) between 2 and 120),
  hotline text check (hotline is null or char_length(hotline) <= 40),
  contact_info text check (contact_info is null or char_length(contact_info) <= 500),
