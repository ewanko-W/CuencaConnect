-- Privileges (Supabase grants broad defaults; narrow them explicitly)
-------------------------------------------------------------------------------
revoke all on public.profiles from anon, authenticated;
grant select on public.profiles to authenticated;
grant update (display_name, barangay_id) on public.profiles to authenticated;

revoke all on public.barangays from anon, authenticated;
grant select on public.barangays to anon, authenticated;
grant insert, update, delete on public.barangays to authenticated;

revoke all on public.offices from anon, authenticated;
grant select, insert, update, delete on public.offices to authenticated;

