-------------------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.barangays enable row level security;
alter table public.offices enable row level security;

-- profiles: residents and staff see their own row; admins see everyone.
create policy profiles_select_own on public.profiles
  for select to authenticated
  using (id = (select auth.uid()));

create policy profiles_select_admin on public.profiles
  for select to authenticated
  using ((select public.is_admin()));

create policy profiles_update_own on public.profiles
  for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

-- No INSERT or DELETE policies: profiles are created only by handle_new_user
-- and removed only by the auth.users cascade.

-- barangays: readable by everyone (registration form); admins manage.
create policy barangays_select_all on public.barangays
  for select to anon, authenticated
  using (true);

create policy barangays_insert_admin on public.barangays
  for insert to authenticated
  with check ((select public.is_admin()));

create policy barangays_update_admin on public.barangays
  for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

create policy barangays_delete_admin on public.barangays
  for delete to authenticated
  using ((select public.is_admin()));

-- offices: the directory is visible to signed-in users; admins manage.
create policy offices_select_active on public.offices
  for select to authenticated
  using (is_active or (select public.is_admin()));

create policy offices_insert_admin on public.offices
  for insert to authenticated
  with check ((select public.is_admin()));

create policy offices_update_admin on public.offices
  for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

create policy offices_delete_admin on public.offices
  for delete to authenticated
  using ((select public.is_admin()));
