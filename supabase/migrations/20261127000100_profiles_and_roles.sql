-- Phase 1: roles, consent, barangays, offices, and profiles with RLS.
--
-- Rules enforced here (see CLAUDE.md):
--   * Roles are resident, office_staff, admin, stored in profiles.role.
--   * Public sign-up always creates a resident; admins and office staff are
--     provisioned manually through app_metadata (not settable by sign-up).
--   * Registration requires explicit consent (version + timestamp).
--   * Office staff must belong to an office.
--   * Access is enforced with RLS and column privileges, not route guards.

-------------------------------------------------------------------------------
-- Types
-------------------------------------------------------------------------------
create type public.user_role as enum ('resident', 'office_staff', 'admin');
create type public.verification_status as enum ('unverified', 'pending', 'approved', 'rejected');

